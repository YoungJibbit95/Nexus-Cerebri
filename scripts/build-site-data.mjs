import { execFileSync } from 'node:child_process';
import { copyFile, readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { basename, dirname, relative, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const generatedDir = resolve(root, 'apps/cerebri-site/src/lib/generated');
const runtimeOutput = resolve(generatedDir, 'runtime-data.ts');
const docsOutput = resolve(generatedDir, 'docs-data.ts');
const staticDir = resolve(root, 'apps/cerebri-site/static');

async function walk(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (['.git', '.idea', 'node_modules', 'site', 'target', 'dist', '.svelte-kit'].includes(entry.name)) continue;
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) result.push(...await walk(path));
    else result.push(path);
  }
  return result;
}

function titleOf(markdown, fallback) {
  return markdown.match(/^#\s+(.+)$/m)?.[1]?.replace(/[\x60*_#]/g, '').trim() ?? fallback;
}

function slugOf(sourcePath) {
  if (sourcePath === 'README.md') return 'project';
  if (sourcePath === 'CHANGELOG.md') return 'changelog';
  if (sourcePath === 'CONTRIBUTING.md') return 'contributing';
  if (sourcePath === 'SECURITY.md') return 'security';
  let slug = sourcePath.replace(/^docs\//, '').replace(/\.md$/, '');
  slug = slug.replace(/(^|\/)README$/i, '$1index').replace(/\/index$/, '');
  return slug || 'index';
}

function runCoreExample(name) {
  const stdout = execFileSync(
    'cargo',
    ['run', '-q', '-p', 'cerebri-core', '--example', name, '--locked'],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }
  );
  return JSON.parse(stdout);
}

const cargo = await readFile(resolve(root, 'Cargo.toml'), 'utf8');
const master = await readFile(resolve(root, 'docs/architecture/specifications/master-v0.4.md'), 'utf8');
const request = JSON.parse(await readFile(resolve(root, 'examples/request.json'), 'utf8'));
const temporalRequest = JSON.parse(await readFile(resolve(root, 'examples/temporal-request.json'), 'utf8'));
const softwareVersion = cargo.match(/\[workspace\.package\][\s\S]*?version = "([^"]+)"/)?.[1];
const rustVersion = cargo.match(/rust-version = "([^"]+)"/)?.[1];
const specVersion = master.match(/Specification version:\*\*\s*([0-9.]+)/)?.[1] ?? '0.4';
if (!softwareVersion || !rustVersion) throw new Error('Cannot derive Cargo version authority');

const all = await walk(root);
const markdownPaths = all
  .filter((path) => path.endsWith('.md'))
  .filter((path) => {
    const source = relative(root, path).split(sep).join('/');
    return source.startsWith('docs/') || ['README.md', 'CHANGELOG.md', 'CONTRIBUTING.md', 'SECURITY.md'].includes(source);
  })
  .sort();

const docs = [];
for (const path of markdownPaths) {
  const sourcePath = relative(root, path).split(sep).join('/');
  const raw = await readFile(path, 'utf8');
  const language = raw.match(/(?:^|\n)lang:\s*(de|en)(?:\n|$)/)?.[1]
    ?? (sourcePath.includes('/de/') ? 'de' : sourcePath.includes('/en/') ? 'en' : 'en');
  const explicitStatus = raw.match(/^Status:\s*(.+)$/mi)?.[1]?.trim() ?? null;
  docs.push({
    slug: slugOf(sourcePath),
    sourcePath,
    sourceUrl: 'https://github.com/YoungJibbit95/Nexus-Cerebri/blob/main/' + sourcePath,
    title: titleOf(raw, basename(sourcePath, '.md')),
    language,
    status: explicitStatus,
    raw
  });
}

let revision = 'working-tree';
try {
  revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
} catch {}

const runtimeData = {
  metadata: {
    softwareVersion,
    specVersion,
    cpirVersion: request.schema_version.major + '.' + request.schema_version.minor,
    rustVersion,
    revision
  },
  request,
  temporalRequest,
  plannerResult: runCoreExample('plan'),
  temporalResult: runCoreExample('temporal')
};

await mkdir(generatedDir, { recursive: true });
await mkdir(staticDir, { recursive: true });
await writeFile(
  runtimeOutput,
  '// Generated by scripts/build-site-data.mjs. Do not edit.\nexport const runtimeData = ' + JSON.stringify(runtimeData, null, 2) + ' as const;\n'
);
await writeFile(
  docsOutput,
  '// Generated by scripts/build-site-data.mjs. Do not edit.\nexport const docsData = ' + JSON.stringify(docs, null, 2) + ' as const;\n'
);
await copyFile(resolve(root, 'assets/nexus-cerebri-logo.png'), resolve(staticDir, 'nexus-cerebri-logo.png'));
console.log('Cerebri site data: ' + docs.length + ' canonical documents, core fixtures generated from Rust.');
